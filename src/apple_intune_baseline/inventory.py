"""Inventory: mSCP setting values reported as Intune macOS custom attributes.

Not compliance: no pass/fail, just what the Mac reports, for a CMDB or reporting.

* One custom attribute per mSCP section (an attribute is one script reporting
  one value, every 8 hours, at most 20 KB). Its value is one flat line:
  ``rule_id=value; rule_id=value; ...; collected=<ISO time>`` where value is the
  raw output of mSCP's check for that rule (multi-line output joined with " | ").
* Not JSON: Intune rejects custom attribute values that look like JSON (tested:
  ``{"a":"b"}`` fails with 0x87D32710 while ``a=b; c=d`` of 2 KB succeeds). Inside
  values, ``"`` becomes ``'``, ``{ <`` become ``(``, ``} >`` become ``)`` and ``;``
  becomes ``,``, so the line splits safely on "; " and the first "=".
* Every rule with an mSCP check is included, also the ones profiles enforce:
  inventory is about what the Mac actually has. Per-user checks (last logged-in
  user) only on request.
* A field dictionary (``<name>.fields.json``) lists per rule the title, section,
  mSCP's expected value and how it is delivered, so the raw values can be read
  without mSCP at hand.
"""

from __future__ import annotations

import base64
import json
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any

from . import classify
from .compliance import (NOT_SCRIPTABLE_TAGS, _arch, _eval_body, _per_user, _zsh_string, expected_output,
                         is_base64_result)

if TYPE_CHECKING:
    from mscp.classes.baseline import Baseline
    from mscp.classes.macsecurityrule import Macsecurityrule

from .platforms import Platform

MAX_VALUE = 200     # characters per rule value
MAX_OUTPUT = 19000  # bytes; Intune allows 20 KB per custom attribute


@dataclass
class SectionInventory:
    section: str
    rules: list[Any] = field(default_factory=list)


def attribute_name(prefix: str, section: str) -> str:
    """Custom attribute name: letters, digits and underscores, e.g. ssmacadmin_mscp_system_settings."""
    base = re.sub(r"[^A-Za-z0-9]+", "_", f"{prefix}_mscp_{section}").strip("_").lower()
    return base[:60]


def select(
    base: Baseline,
    platform: Platform,
    *,
    sections: list[str] | None = None,
    exclude: list[str] | None = None,
    include_per_user: bool = False,
) -> dict[str, Any]:
    if not platform.supports_custom_compliance:  # custom attributes are macOS only
        return {"sections": [], "skipped": [], "not_found": []}
    exclude_set = set(exclude or [])
    plans, skipped, seen = [], [], set()
    for prof in base.profile:
        if sections and prof.section not in sections:
            continue
        plan = SectionInventory(prof.section)
        for rule in prof.rules:
            seen.add(rule.rule_id)
            why = None
            if rule.rule_id in exclude_set:
                why = "left out on request"
            elif not (rule.check or "").strip() or set(rule.tags or []) & NOT_SCRIPTABLE_TAGS \
                    or classify.delivery(rule) == "not_actionable":
                why = "no automated check in mSCP"
            elif _per_user(rule) and not include_per_user:
                why = "reads the last logged-in user's settings (include_per_user to add)"
            if why:
                skipped.append({"rule": rule.rule_id, "why": why})
                continue
            plan.rules.append(rule)
        if plan.rules:
            plans += split(plan)
    return {"sections": plans, "skipped": skipped, "not_found": sorted(exclude_set - seen)}


def worst_size(rules: list[Any]) -> int:
    """Bytes the line could take if every value hit its cap."""
    return sum(len(r.rule_id) + MAX_VALUE + 3 for r in rules) + 40


def split(plan: SectionInventory) -> list[SectionInventory]:
    """One attribute per section, or several ('Operating System (1/2)') when the worst case could
    pass Intune's 20 KB per value."""
    parts: list[list[Any]] = [[]]
    for rule in plan.rules:
        if parts[-1] and worst_size(parts[-1] + [rule]) > MAX_OUTPUT:
            parts.append([])
        parts[-1].append(rule)
    if len(parts) == 1:
        return [plan]
    return [SectionInventory(f"{plan.section} ({i}/{len(parts)})", rules=rs) for i, rs in enumerate(parts, 1)]


def _title(rule: Macsecurityrule) -> str:
    return " ".join(str(rule.title).split())


def inventory_script(plan: SectionInventory, *, name: str, attribute: str, mscp_version: str, baseline: str) -> str:
    """Bash wrapper (Intune wants a shebang) running mSCP's checks in zsh; prints one flat line."""
    lines = [
        "#!/bin/bash",
        f"# {name}",
        f"# Intune custom attribute '{attribute}' (string), generated by apple-intune-baseline",
        f"# from mSCP {mscp_version}, baseline {baseline}, section {plan.section}.",
        "# Inventory only: reports the raw output of mSCP's check per rule as one line:",
        "#   rule_id=value; rule_id=value; ...; collected=<UTC time>",
        "# Not JSON: Intune rejects custom attribute values that look like JSON.",
        "# No pass/fail and no changes to the Mac. Intune runs it every 8 hours.",
        "#",
        "# Rules:",
        *(f"#   {r.rule_id} - {_title(r)}" for r in plan.rules),
        "#",
        "# read -d '' instead of $(cat <<...): bash 3.2 on macOS misparses quotes inside that form.",
        "IFS= read -r -d '' MSCP_INVENTORY <<'MSCP_INVENTORY_END'",
        "export PATH=/usr/bin:/bin:/usr/sbin:/sbin:/usr/libexec",
        "CURRENT_USER=$(/usr/bin/defaults read /Library/Preferences/com.apple.loginwindow lastUserName 2>/dev/null)",
        "CURR_USER_UID=$(/usr/bin/id -u \"$CURRENT_USER\" 2>/dev/null)",
        "arch=$(/usr/bin/arch)",
        "out=''",
        "",
        "# collect <rule_id> <arch> <function>: adds 'rule_id=value; ' to the line",
        "collect() {",
        "  local rule_id=$1 rule_arch=$2 fn=$3 v",
        "  if [[ -n \"$rule_arch\" && \"$arch\" != \"$rule_arch\" ]]; then",
        "    v=\"n/a ($rule_arch only)\"",
        "  else",
        "    v=$($fn 2>/dev/null </dev/null)",
        "  fi",
        "  v=${v//$'\\r'/}",
        "  v=${(j: | :)${(f)v}}                 # lines joined with ' | '",
        "  v=${v//[[:cntrl:]]/ }",
        f"  (( ${{#v}} > {MAX_VALUE} )) && v=\"${{v[1,{MAX_VALUE - 3}]}}...\"",
        "  # Intune rejects values that look like JSON; keep the line flat and splittable",
        "  v=${v//\\\"/\\'}",
        "  v=${v//[\\{<]/(}",
        "  v=${v//[\\}>]/)}",
        "  v=${v//;/,}",
        "  out+=\"$rule_id=$v; \"",
        "}",
        "",
    ]
    for i, rule in enumerate(plan.rules, 1):
        lines += [
            f"# ----- {rule.rule_id}: {_title(rule)}",
            f"check_{i}() {{",
            _eval_body(rule.check),
            "}",
            f"collect {rule.rule_id} {_zsh_string(_arch(rule))} check_{i}",
            "",
        ]
    lines += [
        "out+=\"collected=$(/bin/date -u +%Y-%m-%dT%H:%M:%SZ)\"",
        f"(( ${{#out}} > {MAX_OUTPUT} )) && out=\"error=output over {MAX_OUTPUT} bytes, split the section\"",
        "print -r -- \"$out\"",
        "exit 0",
        "MSCP_INVENTORY_END",
        "exec /bin/zsh --no-rcs -c \"$MSCP_INVENTORY\" </dev/null",
        "",
    ]
    return "\n".join(lines)


def field_info(rule: Macsecurityrule, section: str, parent_values: str = "") -> dict[str, Any]:
    """How to read one rule's reported value: title, section, what mSCP's check prints when the
    rule is met ("expected", exactly as the Mac reports it) and, for base64 output, the readable
    form. 'delivery' says what enforces it (profile, ddm, script...)."""
    info = {"title": _title(rule), "section": section, "expected": expected_output(rule),
            "delivery": classify.delivery(rule), "odv": classify.odv_value(rule, parent_values)}
    if is_base64_result(rule):
        info["encoding"] = "base64"
        info["expected_readable"] = str(rule.result_value)
    return info


def fields(plan: SectionInventory, parent_values: str) -> dict[str, Any]:
    return {r.rule_id: field_info(r, plan.section, parent_values) for r in plan.rules}


def compare(value: str | None, info: dict[str, Any] | None) -> str:
    """'matches' / 'differs' / 'no value' / 'not applicable' / 'unknown rule', against what mSCP's
    check prints when the rule is met. Informational: inventory doesn't judge compliance."""
    if info is None:
        return "unknown rule"
    if value is None or value == "":
        return "no value"
    if value.startswith("n/a ("):
        return "not applicable"
    return "matches" if value.strip() == str(info.get("expected", "")).strip() else "differs"


def readable(value: str, info: dict[str, Any] | None) -> str:
    """Decode base64 values (login window text) for people; other values as reported."""
    if info and info.get("encoding") == "base64" and value:
        import base64 as _b64
        try:
            return _b64.b64decode(value, validate=True).decode("utf-8").rstrip("\n")
        except (ValueError, UnicodeDecodeError):
            return value
    return value


def write(
    result: dict[str, Any],
    out_dir: Path,
    *,
    prefix: str,
    platform: Platform,
    baseline_display: str,
    baseline_name: str,
    os_version: str,
    mscp_version: str,
    parent_values: str,
    attribute_prefix: str,
) -> list[dict[str, Any]]:
    from .generate import _description, policy_name, slug

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    scripts = []
    for plan in result["sections"]:
        name = policy_name(prefix, platform, baseline_display, os_version, plan.section, "Inventory")
        attr = attribute_name(attribute_prefix, plan.section)
        file_sh = f"{slug(name)}.sh"
        script = inventory_script(plan, name=name, attribute=attr, mscp_version=mscp_version, baseline=baseline_name)
        (out_dir / file_sh).write_text(script, encoding="utf-8")
        (out_dir / f"{slug(name)}.fields.json").write_text(
            json.dumps({"attribute": attr, "section": plan.section, "baseline": baseline_name,
                        "fields": fields(plan, parent_values)}, indent=2, ensure_ascii=False, default=str),
            encoding="utf-8")
        titles = {r.rule_id: _title(r) for r in plan.rules}
        body = {
            "@odata.type": "#microsoft.graph.deviceCustomAttributeShellScript",
            "displayName": name,
            "description": _description(mscp_version, baseline_name, plan.section,
                                        [r.rule_id for r in plan.rules], titles),
            "customAttributeName": attr,
            "customAttributeType": "string",
            "scriptContent": base64.b64encode(script.encode("utf-8")).decode(),
            "runAsAccount": "system",
            "fileName": file_sh,
            "roleScopeTagIds": ["0"],
        }
        (out_dir / f"{slug(name)}.json").write_text(json.dumps(body, indent=2), encoding="utf-8")
        scripts.append({"name": name, "section": plan.section, "attribute": attr, "file": f"{slug(name)}.json",
                        "script": file_sh, "fields": f"{slug(name)}.fields.json",
                        "rules": [r.rule_id for r in plan.rules]})
    return scripts


def parse_value(text: str | None) -> dict[str, str] | None:
    """A reported 'rule=value; ...; collected=<time>' line -> {rule: value, "_collected": time}.
    None when it isn't ours (empty, or not rule=value pairs)."""
    out: dict[str, str] = {}
    for part in str(text or "").strip().split("; "):
        key, sep, value = part.partition("=")
        if not sep or not key or " " in key:
            return None
        out["_collected" if key == "collected" else key] = value
    return out or None


OUTDATED_HOURS = 24


def possibly_outdated(reported_at: str | None, last_change: tuple[str, str] | None, now) -> str | None:
    """Why a section's values may not show the Mac as it is now, from Intune's times only (the Mac's
    own 'collected' clock can be off): reported before this baseline's profiles last changed, or
    not reported for a day. Custom attributes run on Intune's schedule, not on every check-in."""
    from datetime import datetime, timedelta

    def when(text):
        try:
            t = datetime.fromisoformat(str(text).replace("Z", "+00:00"))
        except ValueError:
            return None
        return t if t.tzinfo else t.replace(tzinfo=now.tzinfo)

    rep = when(reported_at) if reported_at else None
    if rep is None:
        return None
    if last_change:
        changed = when(last_change[0])
        if changed and rep < changed:
            return (f"reported before '{last_change[1]}' changed ({last_change[0]}); values may predate "
                    "the profile on the Mac")
    if now - rep > timedelta(hours=OUTDATED_HOURS):
        return f"no report for over {OUTDATED_HOURS} hours"
    return None
